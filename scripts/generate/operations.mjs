// Generates the public Transport API modules from the committed OpenAPI document.
//
// The name table is the contract: scripts/generate/transport-names.json maps every
// active Transport operation to a domain and a public method name. Anything active
// and Transport that is missing from the table fails the run, so no operation can
// disappear silently. Office and auth paths are out of scope and ignored.
//
//   node scripts/generate/operations.mjs             regenerate src/transport/generated
//   node scripts/generate/operations.mjs --inventory print the table, write nothing
//   node scripts/generate/operations.mjs --draft      add missing entries with draft names

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const specPath = path.join(root, "spec/normalized.json");
const tablePath = path.join(root, "scripts/generate/transport-names.json");
const outDir = path.join(root, "src/transport/generated");
const HEADER = "// Generated by scripts/generate/operations.mjs. Do not edit by hand.\n";
const METHODS = new Set(["get", "post", "put", "delete", "patch"]);

const spec = JSON.parse(fs.readFileSync(specPath, "utf8"));
const table = JSON.parse(fs.readFileSync(tablePath, "utf8"));
const flags = new Set(process.argv.slice(2));

const fail = (message) => {
  console.error(message);
  process.exit(1);
};

/** terminal_groups -> terminalGroups, posOrder -> posOrder, {id} -> id. */
const camel = (segment) =>
  segment
    .replace(/^\{|\}$/g, "")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part, index) =>
      index === 0 ? part.toLowerCase() : part[0].toUpperCase() + part.slice(1),
    )
    .join("");

/** A draft name from the path tail; the human review is what actually decides. */
const draftName = (tail) => {
  const parts = tail.split("/").filter(Boolean);
  const cleaned = parts[0] === "iiko" ? parts.slice(1) : parts;
  if (cleaned.length === 0) return "list";
  return cleaned
    .map(camel)
    .map((part, index) => (index === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join("");
};

const prefixes = table.prefixes.toSorted((a, b) => b.prefix.length - a.prefix.length);
const ruleFor = (urlPath) =>
  prefixes.find((rule) => urlPath === rule.prefix || urlPath.startsWith(`${rule.prefix}/`));

const active = [];
const deprecated = [];
let foreign = 0;

for (const [urlPath, item] of Object.entries(spec.paths)) {
  const rule = ruleFor(urlPath);
  for (const method of Object.keys(item)) {
    if (!METHODS.has(method)) continue;
    if (!rule) {
      foreign++;
      continue;
    }
    if (item[method].deprecated) {
      deprecated.push(`${method.toUpperCase()} ${urlPath}`);
      continue;
    }
    if (method !== "post") {
      fail(`Transport operation must be POST: ${method.toUpperCase()} ${urlPath}`);
    }
    active.push({ urlPath, op: item[method], domain: rule.domain });
  }
}

const keyOf = (entry) => `${entry.domain}.${entry.name}`;

if (flags.has("--draft")) {
  const taken = new Set(Object.values(table.operations).map((entry) => keyOf(entry)));
  for (const { urlPath, domain } of active) {
    if (table.operations[urlPath]) continue;
    const name = draftName(urlPath.slice(ruleFor(urlPath).prefix.length));
    let candidate = name;
    for (let suffix = 2; taken.has(keyOf({ domain, name: candidate })); suffix++) {
      candidate = `${name}${suffix}`;
    }
    table.operations[urlPath] = { domain, name: candidate };
    taken.add(keyOf({ domain, name: candidate }));
  }
  const sorted = Object.fromEntries(
    Object.entries(table.operations).toSorted(([a], [b]) => a.localeCompare(b)),
  );
  table.operations = sorted;
  fs.writeFileSync(tablePath, `${JSON.stringify(table, null, 2)}\n`);
}

if (flags.has("--inventory")) {
  const byDomain = new Map();
  for (const entry of active) {
    const { domain, name } = table.operations[entry.urlPath] ?? { domain: entry.domain, name: "?" };
    const list = byDomain.get(domain) ?? [];
    list.push({ ...entry, name });
    byDomain.set(domain, list);
  }
  for (const [domain, list] of [...byDomain].toSorted(([a], [b]) => a.localeCompare(b))) {
    console.log(`\n## ${domain} (${list.length})`);
    for (const { name, urlPath, op } of list.toSorted((a, b) => a.name.localeCompare(b.name))) {
      console.log(`  ${name.padEnd(38)} POST ${urlPath}  ${op.summary ?? ""}`);
    }
  }
  console.log(`\n${active.length} active, ${deprecated.length} deprecated, ${foreign} other.`);
  process.exit(0);
}

const missing = active.filter((entry) => !table.operations[entry.urlPath]);
if (missing.length > 0) {
  fail(
    `Unnamed Transport operations — add them to transport-names.json:\n${missing
      .map((entry) => `  POST ${entry.urlPath}`)
      .join("\n")}`,
  );
}

const stale = Object.keys(table.operations).filter(
  (urlPath) => !active.some((entry) => entry.urlPath === urlPath),
);
if (stale.length > 0) {
  fail(`Stale entries in transport-names.json:\n${stale.map((p) => `  ${p}`).join("\n")}`);
}

const owners = new Map();
for (const { urlPath, domain } of active) {
  const { name, domain: entryDomain } = table.operations[urlPath];
  if (entryDomain !== domain) {
    fail(`Wrong domain for ${urlPath}: table says ${entryDomain}, prefix says ${domain}`);
  }
  if (owners.has(keyOf({ domain, name }))) {
    fail(`Duplicate ${domain}.${name}: ${owners.get(keyOf({ domain, name }))} and ${urlPath}`);
  }
  owners.set(keyOf({ domain, name }), urlPath);
}

const restrictionGroup = (description = "") =>
  /Restriction group:\s*`([^`]+)`/.exec(description)?.[1];
const isCommand = (description = "") => /This method is a command/.test(description);
const oneLine = (text) =>
  String(text ?? "")
    .replace(/\s+/g, " ")
    .replace(/^>\s*/, "")
    .trim();

const factoryName = (domain) => `create${domain[0].toUpperCase()}${domain.slice(1)}Resource`;
const fileOf = (domain) => domain.replace(/([A-Z])/g, "-$1").toLowerCase();

// The directory is generated end to end, so a removed domain cannot leave a stale module.
fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

const domains = new Map();
for (const entry of active) {
  const { domain, name } = table.operations[entry.urlPath];
  const list = domains.get(domain) ?? [];
  list.push({ ...entry, name });
  domains.set(domain, list);
}

const written = [];
for (const [domain, list] of [...domains].toSorted(([a], [b]) => a.localeCompare(b))) {
  const lines = list
    .toSorted((a, b) => a.name.localeCompare(b.name))
    .map(({ urlPath, op, name }) => {
      const bodyType = `JsonBody<${JSON.stringify(urlPath)}, "post">`;
      const hasBody = Boolean(op.requestBody);
      const required = op.requestBody?.required === true;
      const args = hasBody ? `body${required ? "" : "?"}: ${bodyType}, ` : "";
      const body = hasBody ? "body, " : "undefined, ";
      const doc = [`    /** ${oneLine(op.summary)}`];
      const group = restrictionGroup(op.description);
      if (group) doc.push(`     *`, `     * Restriction group: \`${group}\`.`);
      if (isCommand(op.description)) {
        doc.push(
          `     *`,
          `     * A command: poll \`commands.status\` with the returned \`correlationId\`.`,
        );
      }
      doc.push(`     */`);
      return [
        ...doc,
        `    ${name}: (${args}init?: CallOptions) =>`,
        `      call(http, "post", ${JSON.stringify(urlPath)}, ${body}init),`,
      ].join("\n");
    });

  const source = [
    HEADER,
    'import type { HttpClient } from "../../http.js";',
    'import { call, type CallOptions, type JsonBody } from "../../operation.js";',
    "",
    `export function ${factoryName(domain)}(http: HttpClient) {`,
    "  return {",
    lines.join("\n"),
    "  };",
    "}",
    "",
  ].join("\n");

  fs.writeFileSync(path.join(outDir, `${fileOf(domain)}.ts`), source);
  written.push({ domain, count: list.length });
}

const index = [
  HEADER,
  'import type { HttpClient } from "../../http.js";',
  ...written.map(
    ({ domain }) => `import { ${factoryName(domain)} } from "./${fileOf(domain)}.js";`,
  ),
  "",
  "/** Every active Transport operation, grouped by domain. */",
  "export function createGeneratedTransport(http: HttpClient) {",
  "  return {",
  ...written.map(({ domain }) => `    ${domain}: ${factoryName(domain)}(http),`),
  "  };",
  "}",
  "",
].join("\n");
fs.writeFileSync(path.join(outDir, "index.ts"), index);

/** Exports every schema under a documented prefix, named by its suffix. */
const aliases = new Map();
for (const { prefix } of table.types ?? []) {
  const keys = Object.keys(spec.components.schemas).filter((key) => key.startsWith(`${prefix}.`));
  if (keys.length === 0) fail(`No schemas under the type prefix: ${prefix}`);
  for (const key of keys) {
    const alias = key.slice(prefix.length + 1);
    if (!/^[A-Za-z_$][\w$]*$/.test(alias)) fail(`Not a usable type name: ${alias} (${key})`);
    if (aliases.has(alias)) fail(`Duplicate type alias ${alias}: ${aliases.get(alias)} and ${key}`);
    aliases.set(alias, key);
  }
}

if (aliases.size > 0) {
  const source = [
    HEADER,
    'import type { components } from "../../generated/schema.js";',
    "",
    ...[...aliases]
      .toSorted(([a], [b]) => a.localeCompare(b))
      .map(
        ([alias, key]) => `export type ${alias} = components["schemas"][${JSON.stringify(key)}];`,
      ),
    "",
  ].join("\n");
  fs.writeFileSync(path.join(outDir, "types.ts"), source);
}

console.log(
  written
    .map((entry) => `${String(entry.count).padStart(4)}  ${fileOf(entry.domain)}.ts`)
    .join("\n"),
);
console.log(
  `\n${active.length} operations in ${written.length} domains, ${deprecated.length} skipped.`,
);
