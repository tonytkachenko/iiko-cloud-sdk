// spec/normalized.json -> public operation modules for both iikoCloud services.
//
//   src/transport/generated/<domain>.ts   flat domains: transport.deliveries.create
//   src/office/generated/<domain>.ts      domain + subresource: office.inventory.incomingInvoice.create
//   <service>/generated/types.ts          <Domain><Method>Params / Response
//   src/generated/operations.ts           active manifest for tests
//
// Transport names are curated in scripts/names/transport.json; Office names are
// derived from the path with explicit overrides. Anything unknown fails the run.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const readJson = (relative) => JSON.parse(fs.readFileSync(path.join(root, relative), "utf8"));
const spec = readJson("spec/normalized.json");
const tables = {
  transport: readJson("scripts/names/transport.json"),
  office: readJson("scripts/names/office.json"),
};
const OUT = {
  transport: path.join(root, "src/transport/generated"),
  office: path.join(root, "src/office/generated"),
};
const HEADER = "// Generated by scripts/generate.mjs. Do not edit by hand.\n";
const METHODS = new Set(["get", "post", "put", "delete", "patch"]);
const IDENT = /^[a-z][A-Za-z0-9]*$/;

const fail = (message) => {
  console.error(message);
  process.exit(1);
};

const camel = (segment) =>
  segment
    .replace(/^\{|\}$/g, "")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part, index) =>
      index === 0 ? part.toLowerCase() : part[0].toUpperCase() + part.slice(1),
    )
    .join("");
const pascal = (value) => value[0].toUpperCase() + value.slice(1);
const oneLine = (text) =>
  String(text ?? "")
    .replace(/<[^>]+>/g, " ")
    .replace(/\*\//g, "* /")
    .replace(/\s+/g, " ")
    .replace(/^>\s*/, "")
    .trim();

const services = Object.entries(tables).map(([service, table]) => {
  const prefixes = table.prefixes.toSorted((a, b) => b.prefix.length - a.prefix.length);
  const versionsPerDomain = new Map();
  for (const rule of prefixRules(prefixes, service)) {
    versionsPerDomain.set(rule.domain, (versionsPerDomain.get(rule.domain) ?? 0) + 1);
  }
  table.multiVersion = versionsPerDomain;
  return { service, table, prefixes, multiVersion: versionsPerDomain };
});

function* prefixRules(prefixes, service) {
  for (const rule of prefixes) yield { ...rule, service };
}

const rules = services
  .flatMap(({ service, prefixes }) => [...prefixRules(prefixes, service)])
  .toSorted((a, b) => b.prefix.length - a.prefix.length);

const ruleFor = (urlPath) =>
  rules.find((rule) => urlPath === rule.prefix || urlPath.startsWith(`${rule.prefix}/`));

const indentOf = (depth) => "  ".repeat(depth);

const signature = (op, indent) => {
  if (op.body === "none") {
    return `${op.name}: (init?: CallOptions): Promise<${op.typeName}Response> =>\n${indent}  t.call(${JSON.stringify(op.path)}, undefined, init),`;
  }
  const params =
    op.body === "optional" ? `body?: ${op.typeName}Params` : `body: ${op.typeName}Params`;
  return `${op.name}: (${params}, init?: CallOptions): Promise<${op.typeName}Response> =>\n${indent}  t.call(${JSON.stringify(op.path)}, body, init),`;
};

const resolveSchema = (node) => {
  if (!node) return undefined;
  return node.$ref ? spec.components.schemas[node.$ref.split("/").pop()] : node;
};

const hasRequired = (node, depth = 0) => {
  if (!node || depth > 10) return false;
  const schema = resolveSchema(node);
  if (!schema) return false;
  if (schema.required?.length) return true;
  return ["allOf", "oneOf", "anyOf"].some((key) =>
    (schema[key] ?? []).some((part) => hasRequired(part, depth + 1)),
  );
};

const bodyKind = (op) => {
  if (!op.requestBody) return "none";
  const schema = op.requestBody.content?.["application/json"]?.schema;
  return op.requestBody.required === true || hasRequired(schema) ? "required" : "optional";
};

const restrictionGroup = (description = "") =>
  /Restriction group:\s*`([^`]+)`/.exec(description)?.[1];
const isCommand = (description = "") => /This method is a command/.test(description);

/** Office names come from the path: <domain>.<subresource>.<method>. */
function deriveOfficeName(rule, urlPath, table) {
  const override = table.overrides?.[urlPath] ?? {};
  const tail = urlPath.slice(rule.prefix.length).split("/").filter(Boolean);
  const subresource =
    "subresource" in override ? override.subresource : tail.length > 1 ? camel(tail[0]) : null;
  const pathMethod = (tail.length > 1 ? tail.slice(1) : tail)
    .map((segment, index) => (index === 0 ? camel(segment) : pascal(camel(segment))))
    .join("");
  let name = override.name ?? (pathMethod || "list");
  if (override.name === undefined && table.multiVersion.get(rule.domain) > 1) {
    name += rule.version.toUpperCase();
  }
  return { domain: override.domain ?? rule.domain, subresource, name };
}

const active = [];
const deprecated = [];
const unmatched = [];
const usedTransport = new Set();
const usedOverrides = new Set();
const publicKeys = new Map();
const typeOwners = new Map();

for (const [urlPath, item] of Object.entries(spec.paths)) {
  for (const method of Object.keys(item)) {
    if (!METHODS.has(method)) continue;
    const op = item[method];
    if (urlPath === "/api/v2/access_token") continue;
    const rule = ruleFor(urlPath);
    if (!rule) {
      if (!op.deprecated) unmatched.push(`${method.toUpperCase()} ${urlPath}`);
      continue;
    }
    if (op.deprecated) {
      // The escape hatch is POST-only; a deprecated GET is not reachable by path.
      if (method === "post") deprecated.push({ service: rule.service, method, path: urlPath });
      continue;
    }
    if (method !== "post")
      fail(`Active operation must be POST: ${method.toUpperCase()} ${urlPath}`);

    let name;
    if (rule.service === "transport") {
      const entry = tables.transport.operations[urlPath];
      if (!entry)
        fail(`Unnamed Transport operation — add it to scripts/names/transport.json: ${urlPath}`);
      if (entry.domain !== rule.domain) {
        fail(`Wrong domain for ${urlPath}: table says ${entry.domain}, prefix says ${rule.domain}`);
      }
      usedTransport.add(urlPath);
      name = { domain: entry.domain, subresource: null, name: entry.name };
    } else {
      if (tables.office.overrides?.[urlPath]) usedOverrides.add(urlPath);
      name = deriveOfficeName(rule, urlPath, tables.office);
    }

    const { domain, subresource } = name;
    for (const part of [domain, subresource, name.name].filter(Boolean)) {
      if (!IDENT.test(part)) fail(`Not a usable name "${part}" for ${urlPath}`);
    }
    const publicKey = `${rule.service}.${domain}.${subresource ? `${subresource}.` : ""}${name.name}`;
    if (publicKeys.has(publicKey)) {
      fail(`Duplicate ${publicKey}: ${publicKeys.get(publicKey)} and ${urlPath}`);
    }
    publicKeys.set(publicKey, urlPath);

    const typeName = pascal(domain) + (subresource ? pascal(subresource) : "") + pascal(name.name);
    if (typeOwners.has(typeName)) {
      fail(`Duplicate type ${typeName}: ${typeOwners.get(typeName)} and ${urlPath}`);
    }
    typeOwners.set(typeName, urlPath);

    active.push({
      service: rule.service,
      domain,
      subresource,
      name: name.name,
      typeName,
      path: urlPath,
      op,
      body: bodyKind(op),
    });
  }
}

if (unmatched.length > 0) fail(`Unmapped operations:\n${unmatched.join("\n")}`);

const staleTransport = Object.keys(tables.transport.operations).filter(
  (p) => !usedTransport.has(p),
);
if (staleTransport.length > 0) {
  fail(`Stale entries in scripts/names/transport.json:\n${staleTransport.join("\n")}`);
}
const staleOverrides = Object.keys(tables.office.overrides ?? {}).filter(
  (p) => !usedOverrides.has(p),
);
if (staleOverrides.length > 0) {
  fail(`Stale entries in scripts/names/office.json:\n${staleOverrides.join("\n")}`);
}

const groupBy = (items, key) => {
  const groups = new Map();
  for (const item of items) {
    const value = key(item);
    groups.set(value, [...(groups.get(value) ?? []), item]);
  }
  return groups;
};

const byService = groupBy(active, (op) => op.service);
const written = [];

for (const { service } of services) {
  const ops = (byService.get(service) ?? []).toSorted(
    (a, b) =>
      a.domain.localeCompare(b.domain) ||
      (a.subresource ?? "").localeCompare(b.subresource ?? "") ||
      a.name.localeCompare(b.name),
  );
  const outDir = OUT[service];
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });

  // --- types.ts
  const types = [HEADER, 'import type { RequestOf, ResponseOf } from "../../core/types.js";', ""];
  for (const op of ops) {
    if (op.body !== "none") {
      types.push(`export type ${op.typeName}Params = RequestOf<${JSON.stringify(op.path)}>;`);
    }
    types.push(`export type ${op.typeName}Response = ResponseOf<${JSON.stringify(op.path)}>;`);
  }
  fs.writeFileSync(path.join(outDir, "types.ts"), `${types.join("\n")}\n`);

  // --- one file per domain, subresources nested for Office
  const byDomain = groupBy(ops, (op) => op.domain);
  const factories = [];

  for (const [domain, domainOps] of [...byDomain].toSorted(([a], [b]) => a.localeCompare(b))) {
    const file = domain.replace(/([A-Z])/g, "-$1").toLowerCase();
    const factory = `create${pascal(domain)}Resource`;
    factories.push({ domain, factory, file });

    const imports = new Set();
    for (const op of domainOps) {
      imports.add(`${op.typeName}Response`);
      if (op.body !== "none") imports.add(`${op.typeName}Params`);
    }
    const doc = (op, indent) => {
      const lines = [`${indent}/** ${oneLine(op.op.summary)}`];
      const group = restrictionGroup(op.op.description);
      if (group) lines.push(`${indent} *`, `${indent} * Restriction group: \`${group}\`.`);
      if (isCommand(op.op.description)) {
        lines.push(
          `${indent} *`,
          `${indent} * A command: poll \`commands.status\` with the returned \`correlationId\`.`,
        );
      }
      lines.push(`${indent} */`);
      return lines.join("\n");
    };

    const lines = [
      HEADER,
      'import type { Transport } from "../../core/transport.js";',
      'import type { CallOptions } from "../../core/types.js";',
      "import type {",
      ...[...imports].toSorted().map((name) => `  ${name},`),
      '} from "./types.js";',
      "",
      `export function ${factory}(t: Transport) {`,
      "  return {",
    ];

    if (service === "transport") {
      for (const op of domainOps) {
        lines.push(doc(op, indentOf(2)));
        lines.push(`${indentOf(2)}${signature(op, indentOf(2))}`);
      }
    } else {
      const direct = domainOps.filter((op) => op.subresource === null);
      for (const op of direct) {
        lines.push(doc(op, indentOf(2)));
        lines.push(`${indentOf(2)}${signature(op, indentOf(2))}`);
      }
      const bySub = groupBy(
        domainOps.filter((op) => op.subresource !== null),
        (op) => op.subresource,
      );
      for (const [subresource, subOps] of [...bySub].toSorted(([a], [b]) => a.localeCompare(b))) {
        lines.push(`    ${subresource}: {`);
        for (const op of subOps) {
          lines.push(doc(op, indentOf(3)));
          lines.push(`${indentOf(3)}${signature(op, indentOf(3))}`);
        }
        lines.push("    },");
      }
    }

    lines.push("  };", "}", "");
    fs.writeFileSync(path.join(outDir, `${file}.ts`), lines.join("\n"));
  }

  // --- service index
  const index = [
    HEADER,
    'import type { Transport } from "../../core/transport.js";',
    ...factories.map(({ factory, file }) => `import { ${factory} } from "./${file}.js";`),
    "",
    `export function createGenerated${pascal(service)}(t: Transport) {`,
    "  return {",
    ...factories.map(({ domain, factory }) => `    ${domain}: ${factory}(t),`),
    "  };",
    "}",
    "",
  ];
  fs.writeFileSync(path.join(outDir, "index.ts"), index.join("\n"));
  written.push({
    service,
    domains: factories.length,
    types: typeNames(ops),
    operations: ops.length,
  });
}

function typeNames(ops) {
  return ops.reduce((sum, op) => sum + (op.body === "none" ? 1 : 2), 0);
}

// --- manifest for tests and the path-typed escape hatch
const manifest = [
  HEADER,
  "export const OPERATIONS = [",
  ...active
    .toSorted(
      (a, b) =>
        a.service.localeCompare(b.service) ||
        a.domain.localeCompare(b.domain) ||
        (a.subresource ?? "").localeCompare(b.subresource ?? "") ||
        a.name.localeCompare(b.name),
    )
    .map((op) =>
      [
        "  {",
        `    service: ${JSON.stringify(op.service)},`,
        `    domain: ${JSON.stringify(op.domain)},`,
        `    subresource: ${JSON.stringify(op.subresource)},`,
        `    method: ${JSON.stringify(op.name)},`,
        `    typeName: ${JSON.stringify(op.typeName)},`,
        `    path: ${JSON.stringify(op.path)},`,
        `    body: ${JSON.stringify(op.body)},`,
        "  },",
      ].join("\n"),
    ),
  "] as const;",
  "",
  "export const DEPRECATED_OPERATIONS = [",
  ...[...new Set(deprecated.map((op) => op.path))]
    .toSorted((a, b) => a.localeCompare(b))
    .map((p) => `  ${JSON.stringify(p)},`),
  "] as const;",
  "",
];
fs.writeFileSync(path.join(root, "src/generated/operations.ts"), manifest.join("\n"));

for (const entry of written) {
  console.log(
    `${entry.service}: ${entry.operations} operations, ${entry.domains} domains, ${entry.types} types`,
  );
}
console.log(`deprecated: ${deprecated.length} (no wrappers, reachable through call)`);
